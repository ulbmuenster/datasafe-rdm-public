const FormTitle = (permissions) => {
    const showButton = permissions?.permissions?.["can_delete_draft"];
    const {values} = useFormikContext();
    return (
        <div id="draft-title">
            <div id="draft-title-icon">
                <img src="../../../../static/images/draft.svg" alt=""/>
            </div>
            <div id="draft-title-content">
                <div id="text">
                    <p>{i18next.t("Archive data")}</p>
                    <h3>{values.metadata?.title || "Untitled"}</h3>
                </div>
                <div id="draft-title-actions">
                    {showButton && (
                        <DeleteButton
                            type="button"
                            id="delete-button"
                            icon="trash alternate outline"
                            className="tertiary"
                        />
                    )}
                </div>
            </div>
        </div>
    );
};

const AddMyselfButton = () => {
    const {values, setFieldValue} = useFormikContext();
    const [userObject, setUserObject] = useState();
    const currentUserEmail = document.querySelector("#deposit-form").dataset.currentUserEmail;
    useEffect(() => {
        const url = `/api/names?q=${currentUserEmail}`;
        fetch(url).then(res => res.json()).then(data => setUserObject(data.hits.hits[0]));

    }, []);

    const handleOnClick = () => {
        setFieldValue("metadata.creators",
            [...values.metadata.creators,
                {
                    "person_or_org": {
                        "family_name": userObject["family_name"],
                        "given_name": userObject["given_name"],
                        "name": `${userObject["family_name"]}, ${userObject["given_name"]}`,
                        "type": "personal",
                    },
                    "affiliations": [
                        {
                            "name": userObject.affiliations[0].name,
                        },
                    ],
                    "role": "",
                    "__key": 0,
                }]);
    };
    return (<Button id="add-myself-button" onClick={handleOnClick}>{i18next.t("Add myself as creator")}</Button>);
};

export class RDMDepositForm extends Component {

    constructor(props) {
        super(props);
        this.config = props.config || {};
        const {files, record} = this.props;
        // TODO: Make ALL vocabulary be generated by backend.
        // Currently, some vocabulary is generated by backend and some is
        // generated by frontend here. Iteration is faster and abstractions can be
        // discovered by generating vocabulary here. Once happy with vocabularies,
        // then we can generate it in the backend.
        this.vocabularies = {
            metadata: {
                ...this.config.vocabularies,

                creators: {
                    ...this.config.vocabularies.creators,
                    type: [
                        {text: "Person", value: "personal"},
                        {text: "Organization", value: "organizational"},
                    ],
                },

                contributors: {
                    ...this.config.vocabularies.contributors,
                    type: [
                        {text: "Person", value: "personal"},
                        {text: "Organization", value: "organizational"},
                    ],
                },
                identifiers: {
                    ...this.config.vocabularies.identifiers,
                },
            },
        };

        // check if files are present

        this.noFiles = !!(
            !Array.isArray(files.entries) ||
            (!files.entries.length && record.is_published)
        );
        this.noFiles = false;
        if (
            !(!Array.isArray(files.entries) ||
                (!files.entries.length && record.is_published))
        ) {
        } else {
            this.noFiles = true;
        }

        this.sectionsConfig = depositFormSectionsConfig;
        this.severityChecks = severityChecksConfig;
        // hide community header for branded communities
        this.hide_community_selection = this.config.hide_community_selection || false;
    }

    sidebarRef = createRef();

    render() {
        const {
            config,
            record,
            files,
            permissions,
            preselectedCommunity,
            filesLocked,
            groupsEnabled,
            allowEmptyFiles,
            useUppy,
        } = this.props;

        // Adding section id to custom fields UI, to be used for accordions
        const customFieldsUI = this.config.custom_fields.ui.map((section) => ({
            ...section,
            id: section.section.toLowerCase().replace(/\s+/g, "-") + "-section",
        }));
        const UploaderField = useUppy ? UppyUploader : FileUploader;

        return (
            <DepositFormApp
                config={this.config}
                record={record}
                preselectedCommunity={preselectedCommunity}
                files={files}
                permissions={permissions}
            >
                <FormFeedback
                    fieldPath="message"
                    labels={this.config.custom_fields["error_labels"]}
                    sectionsConfig={this.sectionsConfig}
                />
                <Container id="rdm-deposit-form">
                    <Grid>
                        <GridRow>
                            <GridColumn
                                mobile={16}
                                tablet={16}
                                computer={12}
                                id="deposit-form-container"
                            >
                                <FormTitle permissions={permissions}/>

                                <AccordionField
                                    includesPaths={this.sectionsConfig["files-section"]}
                                    severityChecks={this.severityChecks}
                                    active
                                    label={i18next.t("Files")}
                                    id="files-section"
                                >
                                    {this.noFiles && record.is_published && (
                                        <div className="text-align-center pb-10">
                                            <em>{i18next.t("The record has no files.")}</em>
                                        </div>
                                    )}
                                    <Overridable
                                        id="InvenioAppRdm.Deposit.FileUploader.container"
                                        record={record}
                                        config={this.config}
                                        permissions={permissions}
                                        filesLocked={filesLocked}
                                        allowEmptyFiles={allowEmptyFiles}
                                    >
                                        <UploaderField
                                            isDraftRecord={!record.is_published}
                                            quota={this.config.quota}
                                            decimalSizeDisplay={this.config.decimal_size_display}
                                            showMetadataOnlyToggle={permissions?.can_manage_files}
                                            allowEmptyFiles={allowEmptyFiles}
                                            filesLocked={filesLocked}
                                            fileUploadConcurrency={config.fileUploadConcurrency}
                                        />
                                    </Overridable>
                                </AccordionField>

                                {permissions?.["can_manage"] && (
                                    <AccordionField
                                        id="access-rights"
                                        label={i18next.t("Access Rights")}
                                        active={true}
                                    >
                                        <DatasafeRdmShareAccess record={record} permissions={permissions}/>
                                    </AccordionField>
                                )}

                                {/* Metadaten */}
                                <AccordionField
                                    includesPaths={this.sectionsConfig["metadata-section"]}
                                    severityChecks={this.severityChecks}
                                    active
                                    label={i18next.t("Metadata")}
                                    id="metadata-section"
                                >
                                    <TitlesField
                                        options={this.vocabularies.metadata.titles}
                                        fieldPath="metadata.title"
                                        recordUI={record.ui}
                                        required
                                    />

                                    <CreatibutorsField
                                        label={i18next.t("Creators")}
                                        labelIcon="user"
                                        fieldPath="metadata.creators"
                                        roleOptions={this.vocabularies.metadata.creators.role}
                                        schema="creators"
                                        autocompleteNames={this.config.autocomplete_names}
                                        required
                                    />
                                    <AddMyselfButton/>
                                    <DescriptionsField
                                        fieldPath="metadata.description"
                                        options={this.vocabularies.metadata.descriptions}
                                        recordUI={_get(record, "ui", null)}
                                    />

                                    <Overridable
                                        id="InvenioAppRdm.Deposit.PublicationDateField.container"
                                        fieldPath="metadata.publication_date"
                                    >
                                        <PublicationDateField
                                            required
                                            fieldPath="metadata.publication_date"
                                        />
                                    </Overridable>

                                    <Overridable
                                        id="InvenioAppRdm.Deposit.SubjectsField.container"
                                        vocabularies={this.vocabularies}
                                        fieldPath="metadata.subjects"
                                        record={record}
                                    >
                                        <SubjectsField
                                            fieldPath="metadata.subjects"
                                            initialOptions={_get(record, "ui.subjects", null)}
                                            limitToOptions={this.vocabularies.metadata.subjects.limit_to}
                                            searchOnFocus
                                        />
                                    </Overridable>
                                    <Overridable
                                        id="InvenioAppRdm.Deposit.DateField.container"
                                        vocabularies={this.vocabularies}
                                        fieldPath="metadata.dates"
                                    >
                                        <DatesField
                                            fieldPath="metadata.dates"
                                            options={this.vocabularies.metadata.dates}
                                            showEmptyValue
                                        />
                                    </Overridable>
                                    <Overridable
                                        id="InvenioAppRdm.Deposit.FundingField.container"
                                        fieldPath="metadata.funding"
                                    >
                                        <FundingField
                                            fieldPath="metadata.funding"
                                            searchConfig={{
                                                searchApi: {
                                                    axios: {
                                                        headers: {
                                                            Accept: "application/vnd.inveniordm.v1+json",
                                                        },
                                                        url: "/api/awards",
                                                        withCredentials: false,
                                                    },
                                                },
                                                initialQueryState: {
                                                    sortBy: "bestmatch",
                                                    sortOrder: "asc",
                                                    layout: "list",
                                                    page: 1,
                                                    size: 5,
                                                },
                                            }}
                                            label="Awards/Grants"
                                            labelIcon="money bill alternate outline"
                                            deserializeAward={(award) => {
                                                return {
                                                    title: award.title_l10n,
                                                    number: award.number,
                                                    funder: award.funder ?? "",
                                                    id: award.id,
                                                    ...(award.identifiers && {
                                                        identifiers: award.identifiers,
                                                    }),
                                                    ...(award.acronym && {acronym: award.acronym}),
                                                };
                                            }}
                                            deserializeFunder={(funder) => {
                                                return {
                                                    id: funder.id,
                                                    name: funder.name,
                                                    ...(funder.title_l10n && {title: funder.title_l10n}),
                                                    ...(funder.pid && {pid: funder.pid}),
                                                    ...(funder.country && {country: funder.country}),
                                                    ...(funder.country_name && {
                                                        country_name: funder.country_name,
                                                    }),
                                                    ...(funder.identifiers && {
                                                        identifiers: funder.identifiers,
                                                    }),
                                                };
                                            }}
                                            computeFundingContents={(funding) => {
                                                let headerContent,
                                                    descriptionContent,
                                                    awardOrFunder = "";

                                                if (funding.funder) {
                                                    const funderName =
                                                        funding.funder?.name ??
                                                        funding.funder?.title ??
                                                        funding.funder?.id ??
                                                        "";
                                                    awardOrFunder = "funder";
                                                    headerContent = funderName;
                                                    descriptionContent = "";

                                                    // there cannot be an award without a funder
                                                    if (funding.award) {
                                                        const {acronym, title} = funding.award;
                                                        awardOrFunder = "award";
                                                        descriptionContent = funderName;
                                                        headerContent = acronym ? `${acronym} — ${title}` : title;
                                                    }
                                                }
                                                return {headerContent, descriptionContent, awardOrFunder};
                                            }}
                                        />
                                    </Overridable>
                                </AccordionField>
                                {!_isEmpty(customFieldsUI) && (
                                    <Overridable
                                        id="InvenioAppRdm.Deposit.CustomFields.container"
                                        record={record}
                                        customFieldsUI={customFieldsUI}
                                    >
                                        <CustomFields
                                            config={customFieldsUI}
                                            record={record}
                                            templateLoaders={[
                                                (widget) => import(`@templates/custom_fields/${widget}.js`),
                                                () =>
                                                    import(`@js/invenio_rdm_records/src/deposit/customFields`),
                                                () => import(`react-invenio-forms`),
                                            ]}
                                            fieldPathPrefix="custom_fields"
                                        />
                                    </Overridable>
                                )}
                            </GridColumn>
                            <Ref innerRef={this.sidebarRef}>
                                <GridColumn
                                    mobile={16}
                                    tablet={16}
                                    computer={4}
                                    id="deposit-sidebar"
                                    className="deposit-sidebar"
                                >
                                    <Sticky context={this.sidebarRef} offset={20}>
                                        <Overridable
                                            id="InvenioAppRdm.Deposit.CardDepositStatusBox.container"
                                            record={record}
                                            permissions={permissions}
                                            groupsEnabled={groupsEnabled}
                                        >
                                            <Card raised>
                                                <Card.Content>
                                                    <DepositStatusBox/>
                                                </Card.Content>
                                                <Card.Content>
                                                    <Grid>
                                                        {/*<GridColumn*/}
                                                        {/*  computer={8}*/}
                                                        {/*  mobile={16}*/}
                                                        {/*  className="pb-0 left-btn-col"*/}
                                                        {/*  id="preview-column"*/}
                                                        {/*>*/}
                                                        {/*  <PreviewButton id="preview-button" fluid />*/}
                                                        {/*</GridColumn>*/}

                                                        <GridColumn computer={16} mobile={16} id="save-column">
                                                            <SaveButton id="save-button" fluid/>
                                                        </GridColumn>
                                                        <GridColumn width={16} id="publish-column">
                                                            <DatasafePublishButton
                                                                id="publish-button"
                                                                fluid
                                                                record={record}
                                                            />
                                                        </GridColumn>

                                                        {/*<GridColumn width={16} className="pt-0">*/}
                                                        {/*{(record["is_draft"] === null || permissions.can_manage) && (*/}
                                                        {/*  <ShareDraftButton*/}
                                                        {/*    record={record}*/}
                                                        {/*    permissions={permissions}*/}
                                                        {/*    groupsEnabled={groupsEnabled}*/}
                                                        {/*  />*/}
                                                        {/*)}*/}
                                                        {/*</GridColumn>*/}
                                                    </Grid>
                                                </Card.Content>
                                            </Card>
                                        </Overridable>
                                    </Sticky>
                                </GridColumn>
                            </Ref>
                        </GridRow>
                    </Grid>
                </Container>
            </DepositFormApp>
        );
    }
}

RDMDepositForm.propTypes = {
    groupsEnabled: PropTypes.bool.isRequired,
    config: PropTypes.object.isRequired,
    recordRestrictionGracePeriod: PropTypes.number.isRequired,
    allowRecordRestriction: PropTypes.bool.isRequired,
    record: PropTypes.object.isRequired,
    preselectedCommunity: PropTypes.object,
    files: PropTypes.object,
    permissions: PropTypes.object,
    filesLocked: PropTypes.bool,
    allowEmptyFiles: PropTypes.bool,
};

RDMDepositForm.defaultProps = {
    preselectedCommunity: undefined,
    permissions: null,
    files: null,
    filesLocked: false,
    allowEmptyFiles: true,
};
